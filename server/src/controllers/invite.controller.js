/**
 * controllers/invite.controller.js
 *
 * Handles the full invite token lifecycle:
 *   POST   /api/invites/:roomCode/generate  → owner/member generates an invite token
 *   GET    /api/invites/:token              → anyone can peek invite details (no auth required)
 *   POST   /api/invites/:token/accept       → authenticated user accepts the invite
 *   DELETE /api/invites/:token              → owner revokes an invite
 */
const RoomInvite = require('../models/RoomInvite');
const Room = require('../models/Room');
const roomService = require('../services/room.service');
const ApiError = require('../utils/ApiError');
const { getPublicTunnelUrl } = require('../services/tunnel.service');
const { CLIENT_URL } = require('../config/env');

/**
 * Resolve the correct public-facing frontend base URL for invite links.
 *
 * Priority:
 *  1. Active tunnel URL — e.g. https://codecollab-live-session.loca.lt
 *     (tunnel points at port 5000 which also serves the built client)
 *  2. CLIENT_URL from .env — correct for each environment:
 *       dev  → http://localhost:5173  (Vite dev server)
 *       prod → https://your-deployed-app.vercel.app
 *  3. Derive from the inbound request as an absolute last resort
 *     (e.g. in scripts/tests that call the API directly)
 */
const resolveInviteBase = (req) => {
  if (getPublicTunnelUrl()) return getPublicTunnelUrl();
  if (CLIENT_URL) return CLIENT_URL.replace(/\/$/, ''); // strip trailing slash
  return `${req.protocol}://${req.get('host')}`;
};

// ─── Generate Invite ────────────────────────────────────────────────────────

const generateInvite = async (req, res, next) => {
  try {
    const { roomCode } = req.params;
    const userId = req.user._id;

    // 1. Room must exist and user must be a member (or owner)
    const room = await Room.findOne({ roomCode });
    if (!room) return next(ApiError.notFound('Room not found'));
    if (!room.isMember(userId)) return next(ApiError.forbidden('You must be a member of this room to invite others'));

    // 2. Create the invite document — token is generated by model default
    const invite = await RoomInvite.create({
      room: room._id,
      roomCode: room.roomCode,
      createdBy: userId,
    });

    // 3. Build the public invite URL.
    //    resolveInviteBase() picks: tunnel URL → CLIENT_URL env → req origin (fallback)
    const inviteUrl = `${resolveInviteBase(req)}/invite/${invite.token}`;

    res.status(201).json({
      success: true,
      invite: {
        token: invite.token,
        roomCode: invite.roomCode,
        expiresAt: invite.expiresAt,
        inviteUrl,
      },
    });
  } catch (err) {
    next(err);
  }
};

// ─── Peek Invite (public — no auth needed) ───────────────────────────────────

const peekInvite = async (req, res, next) => {
  try {
    const { token } = req.params;

    const invite = await RoomInvite.findOne({ token })
      .populate('room', 'name roomCode maxMembers members status')
      .populate('createdBy', 'name');

    if (!invite) return next(ApiError.notFound('Invite link is invalid or does not exist'));

    // Check validity — give specific error messages so the frontend can render appropriately
    if (invite.revoked) {
      return res.status(410).json({ success: false, code: 'REVOKED', message: 'This invite link has been revoked by the owner' });
    }
    if (new Date() > invite.expiresAt) {
      return res.status(410).json({ success: false, code: 'EXPIRED', message: 'This invite link has expired (valid for 7 days)' });
    }
    if (invite.room.status === 'closed') {
      return res.status(410).json({ success: false, code: 'ROOM_CLOSED', message: 'This room has been closed' });
    }
    if (invite.maxUses !== null && invite.usedBy.length >= invite.maxUses) {
      return res.status(410).json({ success: false, code: 'MAX_USES', message: 'This invite link has reached its maximum usage limit' });
    }

    res.json({
      success: true,
      invite: {
        token: invite.token,
        roomCode: invite.roomCode,
        roomName: invite.room?.name,
        memberCount: invite.room?.members?.length ?? 0,
        maxMembers: invite.room?.maxMembers,
        invitedBy: invite.createdBy?.name,
        expiresAt: invite.expiresAt,
      },
    });
  } catch (err) {
    next(err);
  }
};

// ─── Accept Invite (requires authentication) ─────────────────────────────────

const acceptInvite = async (req, res, next) => {
  try {
    const { token } = req.params;
    const userId = req.user._id;

    // 1. Load and validate the invite
    const invite = await RoomInvite.findOne({ token }).populate('room');
    if (!invite) return next(ApiError.notFound('Invite link is invalid or does not exist'));

    if (!invite.isValid()) {
      if (invite.revoked) return next(ApiError.badRequest('This invite link has been revoked'));
      if (new Date() > invite.expiresAt) return next(ApiError.badRequest('This invite link has expired'));
      return next(ApiError.badRequest('This invite link is no longer valid'));
    }

    if (invite.room.status === 'closed') {
      return next(ApiError.badRequest('This room has been closed'));
    }

    // 2. Check if user already used this specific invite
    if (invite.usedByUser(userId)) {
      // User already accepted — just redirect them to the room (idempotent)
      return res.json({ success: true, roomCode: invite.roomCode, alreadyMember: true });
    }

    // 3. Join the room via existing service (handles already-member and full-room checks)
    let room;
    try {
      room = await roomService.joinRoom(invite.roomCode, userId);
    } catch (err) {
      // If room is full, propagate the error
      if (err.statusCode === 403 && err.message.includes('full')) return next(err);
      // If already a member (409 or isMember check inside joinRoom), that's fine
      if (err.statusCode === 409) {
        return res.json({ success: true, roomCode: invite.roomCode, alreadyMember: true });
      }
      return next(err);
    }

    // 4. Record usage on the invite
    invite.usedBy.push({ user: userId, usedAt: new Date() });
    await invite.save();

    res.json({
      success: true,
      roomCode: invite.roomCode,
      room: {
        name: room.name,
        roomCode: room.roomCode,
      },
    });
  } catch (err) {
    next(err);
  }
};

// ─── Revoke Invite ───────────────────────────────────────────────────────────

const revokeInvite = async (req, res, next) => {
  try {
    const { token } = req.params;
    const userId = req.user._id;

    const invite = await RoomInvite.findOne({ token }).populate('room');
    if (!invite) return next(ApiError.notFound('Invite not found'));

    // Only the room owner or the invite creator can revoke
    const room = invite.room;
    const isOwner = room.isOwner(userId);
    const isCreator = invite.createdBy.toString() === userId.toString();
    if (!isOwner && !isCreator) return next(ApiError.forbidden('Only the room owner or invite creator can revoke this invite'));

    invite.revoked = true;
    await invite.save();

    res.json({ success: true, message: 'Invite revoked' });
  } catch (err) {
    next(err);
  }
};

// ─── List Room Invites (owner only) ──────────────────────────────────────────

const listRoomInvites = async (req, res, next) => {
  try {
    const { roomCode } = req.params;
    const userId = req.user._id;

    const room = await Room.findOne({ roomCode });
    if (!room) return next(ApiError.notFound('Room not found'));
    if (!room.isOwner(userId)) return next(ApiError.forbidden('Only the room owner can list invites'));

    const invites = await RoomInvite.find({ room: room._id })
      .populate('createdBy', 'name')
      .sort({ createdAt: -1 });

    const base = resolveInviteBase(req);

    res.json({
      success: true,
      invites: invites.map((inv) => ({
        token: inv.token,
        inviteUrl: `${base}/invite/${inv.token}`,
        createdBy: inv.createdBy?.name,
        expiresAt: inv.expiresAt,
        usedCount: inv.usedBy.length,
        revoked: inv.revoked,
        isValid: inv.isValid(),
      })),
    });
  } catch (err) {
    next(err);
  }
};

module.exports = { generateInvite, peekInvite, acceptInvite, revokeInvite, listRoomInvites };
